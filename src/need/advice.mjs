// "Does this need a workflow at all?" for the product surface (app/ and both MCP servers): the ROUTER-1 need router
// (./router.mjs) with a plain-words reply. Code only by default: $0, no network, well under a millisecond per request, and
// labelled a HINT, because on held-out requests the code alone misses about a third of the requests that need a workflow.
// A judge is optional and must be passed in by the host (a ModelPort-backed judge from ./router.mjs modelJudge, ideally wrapped in
// cappedJudge); with one, the cascade runs (code clears clear negatives, the judge decides the rest). Nothing here reads a key or
// picks a model.
//
// Every answer carries the MEASURED operating point of the decider that produced it at the sensitivity it was asked with
// (reliability.json, generated by experiments/need-router/router1/addendum.mjs from the ROUTER-1 rows), with its evidence grade;
// a sensitivity that was not measured says "uncalibrated" (docs/ROADMAP.md §2.8: each slider position shows its measured
// operating point, or "uncalibrated").
import { readFileSync } from 'node:fs';
import { needCheck, needCascade, clampSensitivity, DEFAULT_SENSITIVITY } from './router.mjs';

export const RELIABILITY = Object.freeze(JSON.parse(readFileSync(new URL('./reliability.json', import.meta.url), 'utf8')));
const POINTS = Object.keys(RELIABILITY.points.code).map(Number).sort((a, b) => a - b);

const pct = (a, b) => `${Math.round((100 * a) / b)}%`;
function pointText(decider, s, m) {
  const who = decider === 'code' ? 'Code only' : `Code pre-filter plus ${decider.replace('cascade:', '')}`;
  if (s <= 0) return `${who}, sensitivity 0: never suggests a workflow (it caught 0 of ${m.positives} that need one).`;
  if (s >= 1) return `${who}, sensitivity 1: always suggests a workflow (also for all ${m.negatives} requests that do not need one).`;
  return `${who}, sensitivity ${s}: on the ${m.n} ROUTER-1 test requests it caught ${m.tp} of ${m.positives} that need a workflow (${pct(m.tp, m.positives)}) and wrongly suggested one for ${m.fp} of ${m.negatives} that do not (${pct(m.fp, m.negatives)}; 95% upper bound ${Math.round(m.fpUpper95 * 100)}%).`;
}

/**
 * The measured operating point for a decider at a sensitivity. decider: 'code', or 'cascade:<model id>'. Returns
 * { calibrated, statement, grade, point? }; a sensitivity or decider without a measurement is "uncalibrated".
 */
export function reliabilityFor(decider, sensitivity) {
  const s = clampSensitivity(sensitivity), table = RELIABILITY.points[decider];
  const grade = RELIABILITY.grade[decider] ?? 'not measured';
  if (!table) return { calibrated: false, decider, sensitivity: s, grade, statement: `Uncalibrated: ${decider} was never measured on the ROUTER-1 set.` };
  const hit = POINTS.find(p => Math.abs(p - s) < 1e-9);
  if (hit === undefined) {
    const lo = Math.max(...POINTS.filter(p => p < s)), hi = Math.min(...POINTS.filter(p => p > s));
    return { calibrated: false, decider, sensitivity: s, grade, statement: `Uncalibrated at sensitivity ${s}: measured only at ${POINTS.join(', ')}. Between them: ${pointText(decider, lo, table[String(lo)].test)} ${pointText(decider, hi, table[String(hi)].test)}` };
  }
  const point = table[String(hit)].test;
  return { calibrated: true, decider, sensitivity: s, grade, point, statement: pointText(decider, hit, point) };
}

const SAY = {
  none: 'No workflow needed: just do it directly.',
  checklist: 'No workflow needed, but it has an irreversible effect: write a short plan and check the result before and after.',
  workflow: 'This needs a workflow: it has steps that must be checked, waited on or applied to many items.',
  recurring: 'This needs a recurring workflow: it repeats on a schedule or trigger.'
};
const HINT = 'Code-only hint (no model judged it): ';

/** The router's decision trimmed for people and agents. `context` hints (recurrence, systems, volume, irreversible...) only raise need. */
export async function needAdvice({ request, sensitivity = DEFAULT_SENSITIVITY, context = {}, judge = null } = {}) {
  const card = judge ? await needCascade(request, { sensitivity, context, judge }) : needCheck(request, { sensitivity, context });
  const reasons = card.primitives.slice(0, 4).map(p => ({ signal: p.name, strength: Math.round(p.score * 100) / 100, words: p.cues.slice(0, 2).map(c => c.match) }));
  const against = card.dampeners.slice(0, 3).map(d => ({ signal: d.name, strength: Math.round(d.score * 100) / 100 }));
  // basis: what the decision rests on. 'cascade' (a judge was plugged in and the cascade decided, judge call or code clearing),
  // 'code' (no judge), 'code (judge fault)' (a judge was plugged in but did not answer), 'slider' (s = 0 or 1).
  const slider = card.sensitivity <= 0 || card.sensitivity >= 1;
  const basis = slider ? 'slider' : !card.cascade ? 'code' : card.decidedBy === 'code (judge fault)' ? 'code (judge fault)' : 'cascade';
  const decider = basis === 'cascade' || (slider && card.cascade) ? `cascade:${card.cascade.model}` : 'code';
  const rel = reliabilityFor(decider, card.sensitivity);
  const hint = basis === 'code' || basis === 'code (judge fault)';
  const fault = basis === 'code (judge fault)' ? ` The model judge did not answer (${card.judge?.fault?.code ?? 'fault'}), so this is the code's decision.` : '';
  return {
    ok: true, needsWorkflow: card.needsWorkflow, mode: card.mode, sensitivity: card.sensitivity, basis, hint,
    decidedBy: card.decidedBy,
    // The deciding score and its bar (the judge's percent and bar when a judge decided), and the code's own score beside it.
    probability: card.score.p, threshold: card.score.threshold, scoreBy: card.score.by, codeProbability: card.p, codeThreshold: card.threshold,
    why: card.why, reasons, against,
    say: `${hint ? HINT : ''}${SAY[card.mode]}${fault}`,
    reliability: `${rel.statement}${slider ? '' : ` ${rel.grade[0].toUpperCase()}${rel.grade.slice(1)}.`}${hint ? ' Treat it as a hint.' : ''}`,
    measured: { decider, calibrated: rel.calibrated, ...(rel.point ? { point: rel.point } : {}), grade: rel.grade },
    router: card.router, ...(card.judge ? { judge: card.judge } : {}), ...(card.cascade ? { cascade: card.cascade } : {})
  };
}

const contextSchema = { type: 'object', additionalProperties: false, description: 'Optional facts that only raise need: a known schedule, the systems or people involved, how many items, whether an effect cannot be undone.',
  properties: { recurrence: { type: 'string', maxLength: 60 }, waits: { type: 'boolean' }, systems: { type: 'array', maxItems: 30, items: { type: 'string', maxLength: 60 } },
    parties: { type: 'array', maxItems: 30, items: { type: 'string', maxLength: 60 } }, volume: { type: 'integer', minimum: 0 }, irreversible: { type: 'boolean' }, audit: { type: 'boolean' }, rules: { type: 'boolean' }, reuse: { type: 'boolean' } } };

/** What the default (s = 0.5) answer of a decider is worth, in one sentence, from reliability.json. */
export function operatingPointSentence(decider) {
  const m = RELIABILITY.points[decider]?.['0.5']?.test;
  if (!m) return 'Its reliability was never measured.';
  return `At the default sensitivity it caught ${pct(m.tp, m.positives)} of the ROUTER-1 test requests that need a workflow and wrongly suggested one for ${pct(m.fp, m.negatives)} of those that do not (${RELIABILITY.grade[decider]})`;
}

/**
 * One tool spec, shared by the app MCP server (need_check) and the engine MCP server (foundry_need_check).
 * judge: the policy model id of the host's judge, or null for code only (the description must say what the tool really does).
 */
export function needToolSpec(name = 'need_check', { judge = null } = {}) {
  const v1 = RELIABILITY.preregisteredV1AtDefault;
  const what = judge
    ? `A free code pre-filter clears clear negatives; a cheap model (${judge}) judges the rest. ${operatingPointSentence(`cascade:${judge}`)}.`
    : `Code only, free and instant, and only a HINT: the preregistered code router caught ${pct(v1.tp, v1.positives)} of held-out requests that need a workflow and wrongly suggested one for ${pct(v1.fp, v1.negatives)} of those that do not; do not tell the person "no workflow needed" on its word alone.`;
  return {
    name,
    description: `Before building anything, check whether a request needs a workflow at all: none (just do it), checklist (one sitting, irreversible effect), workflow, or recurring workflow. ${what} Every answer states its measured reliability. sensitivity 0..1 is the user's slider: 0 never suggests a workflow, 1 always does, 0.5 is the default. Pass the person's exact words in request.`,
    inputSchema: { type: 'object', additionalProperties: false, required: ['request'],
      properties: { request: { type: 'string', minLength: 1, maxLength: 30000 }, sensitivity: { type: 'number', minimum: 0, maximum: 1 }, context: contextSchema } }
  };
}
