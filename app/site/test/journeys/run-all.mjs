// Run every journey, one file at a time, from a clean screenshot folder; then check the screenshot budget (< 25 MB) and write
// the journey log: research/onboarding-20261021/JOURNEYS.json (machine) and JOURNEYS.md (every step, ask, time and screenshot).
// Development evidence, scripted, no users. node app/site/test/journeys/run-all.mjs [--only p2-operator,crawl] [--log-only]
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(here, '..', '..', '..', '..');
const RESEARCH = path.join(ROOT, 'research', 'onboarding-20261021');
const OUT = process.env.FOUNDRY_SHOTS ?? path.join(RESEARCH, 'shots');
const SUMMARY = path.join(RESEARCH, 'JOURNEYS.json');
const LOG = path.join(RESEARCH, 'JOURNEYS.md');
const BUDGET = 25 * 1024 * 1024;
const FILES = ['p2-operator', 'p3-team-lead', 'p1-agents', 'p4-it', 'p5-auditor', 'org-map', 'keys', 'import', 'crawl'];

const only = process.argv.includes('--only') ? process.argv[process.argv.indexOf('--only') + 1].split(',') : null;
const logOnly = process.argv.includes('--log-only'); // rewrite JOURNEYS.md from the files already there
if (!only && !logOnly) { rmSync(OUT, { recursive: true, force: true }); rmSync(SUMMARY, { force: true }); }
mkdirSync(OUT, { recursive: true });

const results = [];
for (const f of logOnly ? [] : FILES.filter(x => !only || only.includes(x))) {
  const started = Date.now();
  const nice = spawnSync('nice', ['--version'], { stdio: 'ignore' }).status === 0;
  const [cmd, args] = nice ? ['nice', [process.execPath, '--test', '--test-concurrency=1', path.join(here, `${f}.mjs`)]] : [process.execPath, ['--test', '--test-concurrency=1', path.join(here, `${f}.mjs`)]];
  const r = spawnSync(cmd, args, { cwd: ROOT, encoding: 'utf8', timeout: 15 * 60 * 1000, env: { ...process.env } });
  const out = `${r.stdout}\n${r.stderr}`;
  const pass = Number(out.match(/ℹ pass (\d+)/)?.[1] ?? 0), fail = Number(out.match(/ℹ fail (\d+)/)?.[1] ?? 0);
  results.push({ file: `${f}.mjs`, pass, fail, ms: Date.now() - started, failures: out.split('\n').filter(l => /^✖ /.test(l)).slice(0, 10) });
  process.stdout.write(`${fail || r.status ? 'FAIL' : 'ok  '} ${f}.mjs  ${pass} passed, ${fail} failed  (${Math.round((Date.now() - started) / 1000)} s)\n`);
  if (fail || r.status) process.stdout.write(out.split('\n').filter(l => /^✖|Error|assert/i.test(l)).slice(0, 30).join('\n') + '\n');
}

// The screenshot budget.
const walk = dir => existsSync(dir) ? readdirSync(dir).flatMap(x => statSync(path.join(dir, x)).isDirectory() ? walk(path.join(dir, x)) : [path.join(dir, x)]) : [];
const all = walk(OUT);
const shotBytes = all.filter(x => x.endsWith('.jpg')).reduce((s, x) => s + statSync(x).size, 0);
const totalBytes = all.reduce((s, x) => s + statSync(x).size, 0);
const summary = existsSync(SUMMARY) ? JSON.parse(readFileSync(SUMMARY, 'utf8')) : { journeys: {} };
summary.run = { at: logOnly ? summary.run?.at ?? new Date().toISOString() : new Date().toISOString(), files: logOnly ? summary.run?.files ?? [] : results, screenshots: all.filter(x => x.endsWith('.jpg')).length, screenshotBytes: shotBytes, folderBytes: totalBytes, budgetBytes: BUDGET };
writeFileSync(SUMMARY, `${JSON.stringify(summary, null, 2)}\n`);

// The human-readable log: every step of every persona journey.
const rel = x => path.relative(RESEARCH, x).split(path.sep).join('/');
const fmt = ms => `${(ms / 1000).toFixed(1)} s`;
const lines = ['# Journey log (development evidence, scripted, no users)', '',
  `Generated by \`app/site/test/journeys/run-all.mjs\` on ${summary.run.at.slice(0, 10)}. Steps and asks are counted by the harness (\`harness.mjs\`):`,
  'a step is any person action (click, fill, choose, upload, key, or an action outside the browser such as pasting a line); an ask',
  'is an action on a control that carries `data-ask` (a question whose wrong answer would harm, or an irreversible yes). Times are',
  'scripted wall-clock on a shared container, not human time. Preconditions are listed, not counted.', '',
  `Screenshots: ${summary.run.screenshots} JPEG files, ${(shotBytes / 1048576).toFixed(1)} MB (budget 25 MB).`, '',
  '## Summary', '', '| Journey | Variant | Passed | Steps | Asks | Milestones (steps / asks / time) | Errors | Refusals shown | A11y issues | Shots |', '|---|---|---|---|---|---|---|---|---|---|'];
for (const [name, j] of Object.entries(summary.journeys)) {
  if (name.startsWith('crawl')) continue;
  const ms = Object.entries(j.milestones ?? {}).map(([k, m]) => `${k}: ${m.steps} / ${m.asks} / ${fmt(m.ms)}`).join('; ');
  lines.push(`| ${name.split(' ')[0]} | ${j.variant.replace(/^-/, '')} | ${j.passed ? 'yes' : 'NO'} | ${j.steps} | ${j.asks} | ${ms || '-'} | ${j.errors} | ${j.refusals ?? 0} | ${j.a11yIssues} | ${j.shots} |`);
}
const crawl = Object.entries(summary.journeys).filter(([n]) => n.startsWith('crawl'));
if (crawl.length) {
  lines.push('', '## Crawl', '', '| State | Width | Passed | Pages checked | Problems | A11y issues |', '|---|---|---|---|---|---|');
  for (const [name, j] of crawl) lines.push(`| ${name.split(' ')[0].replace('crawl-', '')} | ${j.variant.split('-').pop()} | ${j.passed ? 'yes' : 'NO'} | ${j.checks?.pages ?? '-'} | ${j.checks?.problems?.length ?? '-'} | ${j.a11yIssues} |`);
}
for (const dir of readdirSync(OUT).filter(d => d !== 'crawl' && statSync(path.join(OUT, d)).isDirectory()).sort()) {
  for (const file of readdirSync(path.join(OUT, dir)).filter(x => /^journey.*\.json$/.test(x)).sort()) {
    const j = JSON.parse(readFileSync(path.join(OUT, dir, file), 'utf8'));
    lines.push('', `## ${j.journey} (${j.variant.replace(/^-/, '')})`, '', `Passed: ${j.passed ? 'yes' : 'no'}. ${j.totalSteps} steps, ${j.totalAsks} asks, ${fmt(j.ms)}.` +
      (j.preconditions?.length ? ` Preconditions (not counted): ${j.preconditions.join('; ')}.` : '') + (j.failure ? ` Failure: ${j.failure.split('\n')[0]}` : ''), '',
    '| # | What | Steps | Asks | Time | Screenshot or page |', '|---|---|---|---|---|---|');
    let i = 0;
    for (const s of j.steps) {
      i += 1;
      const what = s.shot ? `screen: ${s.slug}${s.note ? ` (${s.note})` : ''}` : s.action === 'precondition' ? `precondition: ${s.target}` : `${s.action}${s.ask ? ' (ask)' : ''}: ${String(s.target ?? s.key ?? '').replace(/\|/g, '/')}`;
      lines.push(`| ${i} | ${what.replace(/\n/g, ' ')} | ${s.steps} | ${s.asks} | ${fmt(s.ms)} | ${s.shot ? `[${s.shot}](${rel(path.join(OUT, dir, s.shot))})${s.h1 ? ` · ${s.h1.replace(/\|/g, '/')}` : ''}` : ''} |`);
    }
    if (j.checks) lines.push('', '<details><summary>What the journey asserted and recorded</summary>', '', '```json', JSON.stringify(j.checks, null, 2).slice(0, 4000), '```', '', '</details>');
  }
}
writeFileSync(LOG, `${lines.join('\n')}\n`);
process.stdout.write(`\nscreenshots: ${summary.run.screenshots} files, ${(shotBytes / 1048576).toFixed(2)} MB (folder ${(totalBytes / 1048576).toFixed(2)} MB; budget 25 MB)\nlog: ${path.relative(ROOT, LOG)}\n`);
if (totalBytes > BUDGET || results.some(r => r.fail)) process.exitCode = 1;
