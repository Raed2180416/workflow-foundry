#!/usr/bin/env node
// Generates the skill pack's everyday worked examples (skills/foundry-construct/exemplars/app/<id>.json, with their practice cases in
// exemplars/app/practice/<id>.json) from the seven frontier-written examples in app/core/templates/*.json (app/FRONT-DOOR.md). Those
// files stay where they are: the onboarding site's gallery fills them in by form, and the BUILDER-1 and CI-1 manifests freeze them by
// hash. Each worked example is the example filled with its own sample settings and practice data: a plain typed workflow (no
// template:/slots: tags, no slot markers) that validates, lints clean with gating acceptance and passes the front door's practice, so a
// coding agent can learn from one or start from one. They use the app's capabilities (local sheets, the outbox and chat stand-ins), so
// they live in exemplars/app/ and are checked against the app's registry (app/test/front-door.test.mjs), not the engine's default one
// (tests/skillpack.test.mjs lints exemplars/*.json). `--check` exits 1 when a file on disk differs from what the examples produce.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadLibrary, resolveSlots, instantiate, practiceOf } from '../../app/core/library.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const OUT = path.join(root, 'skills', 'foundry-construct', 'exemplars', 'app');
const PRACTICE = path.join(OUT, 'practice');

/** One worked example from one example template: { id, workflow, practice }. */
export function exemplarOf(template) {
  const filled = resolveSlots(template, { slots: template.example, notStated: [], questions: [] }, { text: JSON.stringify(template.example) });
  if (filled.problems.length || filled.questions.length) throw new Error(`${template.id}: its example settings do not fill it (${[...filled.problems, ...filled.questions.map(q => q.id)].join('; ')})`);
  const w = instantiate(template, filled.values, { builder: 'gen-exemplars' });
  const workflow = { ...w, version: 1, metadata: { sources: [`app/core/templates/${template.file} (example "${template.id}", filled with its own sample settings)`],
    rationale: `Worked example for the free-form front door, generated by tools/skillpack/gen-exemplars.mjs from the frontier-written example "${template.id}" (${template.author}). Shows: ${template.whenToUse} Never: ${template.notFor}`.slice(0, 20000) } };
  const world = practiceOf(template);
  return { id: template.id, workflow, practice: { about: `Practice cases for exemplars/app/${template.id}.json (the example's own practice data). Every address in them is a practice address.`,
    practiceInput: [{ name: `${template.id} practice data`, input: world.input, sheets: world.sheets }] } };
}
const text = value => `${JSON.stringify(value, null, 2)}\n`;

export const exemplars = () => loadLibrary().map(exemplarOf);
export const EXEMPLAR_DIR = OUT;
const all = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url) ? exemplars() : [];
if (all.length && process.argv.includes('--check')) {
  const stale = all.flatMap(e => [[path.join(OUT, `${e.id}.json`), text(e.workflow)], [path.join(PRACTICE, `${e.id}.json`), text(e.practice)]])
    .filter(([file, want]) => !existsSync(file) || readFileSync(file, 'utf8') !== want).map(([file]) => path.relative(root, file));
  if (stale.length) { process.stderr.write(`stale worked examples (run node tools/skillpack/gen-exemplars.mjs): ${stale.join(', ')}\n`); process.exitCode = 1; }
} else if (all.length) {
  mkdirSync(PRACTICE, { recursive: true });
  for (const e of all) { writeFileSync(path.join(OUT, `${e.id}.json`), text(e.workflow)); writeFileSync(path.join(PRACTICE, `${e.id}.json`), text(e.practice)); }
  process.stdout.write(`wrote ${all.length} worked examples to ${path.relative(root, OUT)}\n`);
}
