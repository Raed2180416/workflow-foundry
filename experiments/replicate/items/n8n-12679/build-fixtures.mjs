#!/usr/bin/env node
// Regenerates fixtures/recorded-calls.json and fixtures/examples.json. Both are deterministic; item.test.mjs fails if the committed
// files differ from a fresh build, so they cannot drift from the mocks.
//
// recorded-calls.json is the "recorded responses for every external call": for each call the original workflow makes (plus the
// ones improved solutions may use) a request and the response the mock gives, success and one error each. NOTHING here was recorded
// from the real vendors (no network access to third-party services was used or allowed); the responses are the mocks' own,
// shaped after what the definition reads from them.
import { writeFileSync } from 'node:fs';
import { World, API_OPS } from './world.mjs';
import { CONFIG } from './scenarios.mjs';
import { buildExamples } from './examples.mjs';

// node kind in the original definition -> call. Kinds are (node type, resource, operation) or (http method, path); no node names.
export const NODE_KIND_TO_CALL = {
  'klicktipp.subscriber.subscribe': 'klicktipp.subscribe', 'klicktipp.subscriber.update': 'klicktipp.updateSubscriber', 'klicktipp.subscriber.get': 'klicktipp.getSubscriber',
  'klicktipp.subscriber.delete': 'klicktipp.deleteSubscriber', 'klicktipp.contact-tagging': 'klicktipp.tag',
  'zohoCrm.contact.create': 'zoho.createContact', 'zohoCrm.contact.update': 'zoho.updateContact', 'zohoCrm.contact.get': 'zoho.getContact', 'zohoCrm.contact.delete': 'zoho.deleteContact',
  'http.PUT /crm/v3/Contacts': 'zoho.bulkUpdate', 'http.POST /crm/v3/Contacts/actions/add_tags': 'zoho.addTags',
};

export function buildRecordedCalls() {
  const w = new World({ cfg: CONFIG, seed: 'recorded', scenarioId: 'catalogue' });
  const K = CONFIG.klicktipp;
  const rec = [], at = (name, args) => { const r = w.call(name, args).response; rec.push({ call: name, request: args, response: r }); return r; };
  const person = { Last_Name: 'Catalogue', First_Name: 'Cora', Email: 'cora.catalogue@mail.example', Phone: '+49 30 0000001', Date_of_Birth: '1990-05-17' };
  const z = at('zoho.createContact', { fields: person }).body.data[0].details.id;
  at('zoho.createContact', { fields: { First_Name: 'No', Email: 'no.lastname@mail.example' } });
  at('zoho.getContact', { id: z }); at('zoho.getContact', { id: '0' });
  at('zoho.updateContact', { id: z, fields: { Phone: '+49 30 0000002' } }); at('zoho.updateContact', { id: '0', fields: { Phone: 'x' } });
  at('zoho.bulkUpdate', { records: [{ id: z, Email_Opt_Out: true }, { id: '0', Email_Opt_Out: true }] });
  at('zoho.addTags', { ids: [z], tags: [{ name: 'Online Store' }] }); at('zoho.addTags', { ids: [], tags: [] });
  at('zoho.searchContacts', { email: person.Email }); at('zoho.searchContacts', { email: 'nobody@mail.example' });
  const s = at('klicktipp.subscribe', { email: person.Email, listId: K.lists.soi.id, tagId: K.tags.created.id, fields: { fieldFirstName: 'Cora', fieldLastName: 'Catalogue', fieldBirthday: '1990-05-17', [K.fields.zohoContactId]: z } }).body;
  at('klicktipp.subscribe', { email: '', listId: K.lists.soi.id });
  at('klicktipp.getSubscriber', { id: s.id }); at('klicktipp.getSubscriber', { email: 'nobody@mail.example' });
  at('klicktipp.updateSubscriber', { lookupEmail: person.Email, fields: { fieldPhone: '+49 30 0000002' } }); at('klicktipp.updateSubscriber', { id: '0', fields: {} });
  at('klicktipp.tag', { email: person.Email, tagIds: [K.tags.segmentOnline.id] }); at('klicktipp.tag', { email: 'nobody@mail.example', tagIds: [K.tags.segmentOnline.id] });
  at('klicktipp.deleteSubscriber', { id: s.id }); at('klicktipp.deleteSubscriber', { id: s.id });
  at('zoho.deleteContact', { id: z }); at('zoho.deleteContact', { id: z });
  at('state.put', { key: 'k', value: { a: 1 } }); at('state.put', { key: 'k', value: 2, ifVersion: 0 }); at('state.get', { key: 'k' }); at('state.get', { key: 'missing' });
  const covered = new Set(rec.map(r => r.call));
  const missing = API_OPS.filter(o => !covered.has(o));
  if (missing.length) throw new Error(`recorded-calls does not cover ${missing.join(', ')}`);
  return { note: 'Synthetic: responses are the mocks\' own, not recorded from Zoho or KlickTipp. Generated by build-fixtures.mjs from a fresh world (seed "recorded").', nodeKindToCall: NODE_KIND_TO_CALL, calls: rec };
}

export function buildAll() {
  const ex = buildExamples();
  return { 'fixtures/recorded-calls.json': buildRecordedCalls(), 'fixtures/examples.json': { task: ex.task, eventSamples: ex.eventSamples, scenarios: ex.scenarios } };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const [rel, data] of Object.entries(buildAll())) { writeFileSync(new URL(rel, import.meta.url), JSON.stringify(data, null, 1) + '\n'); console.log('wrote', rel); }
}
