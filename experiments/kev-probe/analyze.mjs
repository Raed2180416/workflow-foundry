// Metrics for the Kev probe on the EVALUATION half (thresholds chosen on the CALIBRATION half).
// Writes research/kev-20261007/probe-summary.json and experiments/runs/kev-probe/tables.md.
// Usage: node experiments/kev-probe/analyze.mjs
import path from 'node:path';
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { JudgmentLedger, calibrationReport } from '../../src/judgment.mjs';
import { wilson } from '../lib/stats.mjs';
import { RUN_DIR, ROOT, readJsonl, median, quantile, budget } from './lib.mjs';
import { BUILDERS, loadDataset } from './datasets.mjs';
import { ledgerFile, rawFile, frozen, hostedSubset, HOSTED_MODEL } from './run.mjs';
import { loadPolicy } from '../../src/models/policy.mjs';

const DATASETS = Object.keys(BUILDERS);
const T0 = 2.3510958125672174;           // Kev-0.8B shipped temperature (/v1/models)
const { policy } = loadPolicy();
const IMPUTED_PER_HOUR = policy.providers['llama-server'].imputedComputeUsdPerHour; // 0.2, the policy's local-CPU rate
const CORES = 4;
const r3 = x => (x == null || Number.isNaN(x) ? null : Math.round(x * 1000) / 1000);

// Re-temper served probabilities: p_T ∝ p^(T0/T) (exact up to 4-decimal rounding; floor 1e-5).
function retemper(row, a) {
  const z = row.options.map(o => a * Math.log(Math.max(row.probabilities[o] ?? 0, 1e-5)));
  const m = Math.max(...z), e = z.map(v => Math.exp(v - m)), s = e.reduce((x, y) => x + y, 0);
  const probabilities = Object.fromEntries(row.options.map((o, i) => [o, e[i] / s]));
  const chosen = row.options.reduce((b, o) => (probabilities[o] > probabilities[b] ? o : b), row.options[0]);
  return { ...row, probabilities, chosen, confidence: probabilities[chosen] };
}
const nll = rows => rows.reduce((s, r) => s - Math.log(Math.max(r.probabilities[r.truth] ?? 0, 1e-9)), 0) / rows.length;
function fitPower(cal) {
  let best = { a: 1, nll: nll(cal) };
  for (let a = 0.2; a <= 6.0001; a += 0.05) { const v = nll(cal.map(r => retemper(r, a))); if (v < best.nll) best = { a: Math.round(a * 100) / 100, nll: v }; }
  return best;
}

// Risk/coverage on eval at a threshold chosen on calibration.
function atThreshold(evalRows, t) {
  if (t == null) return { threshold: null, coverage: 0, risk: null, accepted: 0 };
  const acc = evalRows.filter(r => r.confidence >= t), wrong = acc.filter(r => r.chosen !== r.truth).length;
  return { threshold: r3(t), coverage: r3(acc.length / evalRows.length), risk: acc.length ? r3(wrong / acc.length) : null, accepted: acc.length };
}
function metrics(evalRows, calRows) {
  const rep = calibrationReport(evalRows);
  if (!rep.n) return { n: 0 };
  const correct = evalRows.filter(r => r.chosen === r.truth).length;
  const ci = wilson(correct, rep.n);
  const out = { n: rep.n, accuracy: r3(rep.accuracy), ci95: [r3(ci.lo), r3(ci.hi)], brier: r3(rep.brier), ece: r3(rep.ece),
    reliability: rep.reliability.map(b => ({ bin: `${b.lo.toFixed(1)}-${b.hi.toFixed(1)}`, n: b.n, confidence: r3(b.confidence), accuracy: r3(b.accuracy) })) };
  for (const budgetErr of [0.05, 0.10]) {
    const key = `budget${Math.round(budgetErr * 100)}`;
    if (calRows?.length) {
      const cal = calibrationReport(calRows, { errorBudget: budgetErr });
      out[key] = { calThreshold: r3(cal.threshold), calCoverage: r3(cal.coverageAtBudget), eval: atThreshold(evalRows, cal.threshold) };
    } else { // no calibration rows for this engine: in-sample (optimistic) threshold, flagged
      const ins = calibrationReport(evalRows, { errorBudget: budgetErr });
      out[key] = { inSample: true, threshold: r3(ins.threshold), coverage: r3(ins.coverageAtBudget) };
    }
  }
  return out;
}
function mcnemar(a, b) { // exact two-sided on paired correctness
  let x = 0, y = 0;
  for (const [id, ra] of a) { const rb = b.get(id); if (!rb) continue; const ca = ra.chosen === ra.truth, cb = rb.chosen === rb.truth; if (ca && !cb) x++; else if (!ca && cb) y++; }
  const n = x + y, k = Math.min(x, y); let p = 0, c = 1;
  for (let i = 0; i <= k; i++) { if (i > 0) c = c * (n - i + 1) / i; p += c / 2 ** n; }
  return { aOnly: x, bOnly: y, p: r3(Math.min(1, 2 * p)) };
}
const lat = xs => (xs.length ? { medianMs: Math.round(median(xs)), p90Ms: Math.round(quantile(xs, 0.9)), n: xs.length } : null);

const fz = frozen();
const summary = { generated: new Date().toISOString(), evidence: 'DEVELOPMENT (dev-split bed seeds 1-400, generator truth labels; failure-class is generated by the probe)',
  kev: { run: 'jaredpalmer/kev-0.8b@v1.0', device: 'cpu', dtype: 'float32', shippedTemperature: T0 }, hostedModel: HOSTED_MODEL,
  costAssumptions: { kevImputedUsdPerHour: IMPUTED_PER_HOUR, kevCores: CORES, note: 'policy/models.json imputedComputeUsdPerHour=0.2 (llama-server, per wall-hour of the box); per-core-hour reading multiplies by 4 cores. Hosted = CLI-reported list-price USD.' },
  budget: (({ kev, hosted }) => ({ kev, hosted }))(budget()), datasets: {} };
const md = [];

for (const ds of DATASETS) {
  const items = loadDataset(ds);
  if (!items.length) continue;
  const wording = fz[ds]?.wording ?? null;
  const d = { items: items.length, calibrationItems: items.filter(i => i.half === 'calibration').length, evaluationItems: items.filter(i => i.half === 'evaluation').length,
    options: items[0].options.length, baseRate: null, frozenWording: wording, wordingCalibration: fz[ds]?.calibration ?? null, engines: {} };
  const ev = items.filter(i => i.half === 'evaluation');
  const majority = Math.max(...Object.values(ev.reduce((m, i) => ({ ...m, [i.truth]: (m[i.truth] ?? 0) + 1 }), {})));
  d.baseRate = r3(majority / ev.length);

  // Kev
  const kevRows = existsSync(ledgerFile('kev', ds)) ? new JudgmentLedger(ledgerFile('kev', ds)).rows() : [];
  const kCal = kevRows.filter(r => r.split === 'calibration' && r.meta.wording === wording);
  const kEval = kevRows.filter(r => r.split === 'evaluation' && r.meta.wording === wording);
  const kevRaw = readJsonl(rawFile('kev', ds));
  const kEvalRaw = kevRaw.filter(r => r.half === 'evaluation' && !r.error);
  if (kEval.length) {
    const m = metrics(kEval, kCal);
    const wall = kEvalRaw.map(r => r.wallMs), server = kEvalRaw.map(r => r.serverMs).filter(Number.isFinite);
    const meanSec = wall.reduce((a, b) => a + b, 0) / wall.length / 1000;
    m.latency = { wall: lat(wall), server: lat(server), load1Median: r3(median(kEvalRaw.map(r => r.load1))) };
    m.usdPer1000 = { policyWallHour: r3(meanSec * IMPUTED_PER_HOUR / 3600 * 1000), perCoreHour: r3(meanSec * CORES * IMPUTED_PER_HOUR / 3600 * 1000) };
    m.errors = kevRaw.filter(r => r.error).length;
    // workload temperature refit on calibration, applied to evaluation
    const fit = fitPower(kCal);
    const kEvalT = kEval.map(r => retemper(r, fit.a)), kCalT = kCal.map(r => retemper(r, fit.a));
    m.refit = { power: fit.a, impliedTemperature: r3(T0 / fit.a), ...(({ brier, ece, budget5, budget10 }) => ({ brier, ece, budget5, budget10 }))(metrics(kEvalT, kCalT)) };
    // wording agreement on calibration (same argmax under A and B)
    const byItem = new Map();
    for (const r of kevRows.filter(x => x.split === 'calibration')) { if (!byItem.has(r.meta.itemId)) byItem.set(r.meta.itemId, {}); byItem.get(r.meta.itemId)[r.meta.wording] = r.chosen; }
    const pairs = [...byItem.values()].filter(x => x.A && x.B);
    m.wordingAgreementCal = r3(pairs.filter(x => x.A === x.B).length / pairs.length);
    const calWall = kevRaw.filter(r => r.half === 'calibration' && r.wording === 'A' && !r.error);
    m.calibrationLatencyPacked2 = { wall: lat(calWall.map(r => r.wallMs)), inputTokensMedian: median(calWall.map(r => r.inputTokens).filter(Number.isFinite)) };
    d.engines.kev = m;
  }
  // Rule
  const ruleRows = existsSync(ledgerFile('rule', ds)) ? new JudgmentLedger(ledgerFile('rule', ds)).rows() : [];
  const rEval = ruleRows.filter(r => r.split === 'evaluation'), rCal = ruleRows.filter(r => r.split === 'calibration');
  if (rEval.length) { d.engines.rule = metrics(rEval, rCal); d.engines.rule.latency = { wall: lat(rEval.map(r => r.latencyMs)) }; d.engines.rule.usdPer1000 = 0; }
  // Hosted model
  const modelRows = existsSync(ledgerFile('model', ds)) ? new JudgmentLedger(ledgerFile('model', ds)).rows() : [];
  const mRaw = readJsonl(rawFile('model', ds));
  if (modelRows.length) {
    const m = metrics(modelRows, null);
    const ok = mRaw.filter(r => !r.error);
    m.latency = { wall: lat(ok.map(r => r.wallMs)) };
    m.usdPer1000 = r3(ok.reduce((s, r) => s + (r.costUsd ?? 0), 0) / ok.length * 1000);
    m.errors = mRaw.filter(r => r.error).length;
    m.errorCodes = [...new Set(mRaw.filter(r => r.error).map(r => r.error.code))];
    // paired: Kev and rule on exactly the hosted subset
    const sub = new Set(hostedSubset(items).map(i => i.id));
    const pick = rows => new Map(rows.filter(r => sub.has(r.meta.itemId)).map(r => [r.meta.itemId, r]));
    const mm = pick(modelRows), km = pick(kEval), rm = pick(rEval);
    const accOn = map => (map.size ? r3([...map.values()].filter(r => r.chosen === r.truth).length / map.size) : null);
    m.sameSubset = { n: mm.size, model: accOn(mm), kev: accOn(km), rule: accOn(rm), kevVsModel: mcnemar(km, mm), ruleVsModel: mcnemar(rm, mm) };
    // Cascades on the same subset: take the cheap engine's answer when its confidence clears the threshold
    // chosen on ITS calibration half (5% budget), otherwise escalate to the hosted model.
    const modelCost = m.usdPer1000 / 1000;
    const cascade = (cheapMap, calRowsCheap, cheapCostEach) => {
      const t = calibrationReport(calRowsCheap, { errorBudget: 0.05 }).threshold;
      let right = 0, kept = 0, n = 0;
      for (const [id, mr] of mm) {
        const c = cheapMap.get(id); if (!c) continue; n++;
        const take = t != null && c.confidence >= t; if (take) kept++;
        right += (take ? c : mr).chosen === mr.truth;
      }
      return n ? { n, threshold: r3(t), keptShare: r3(kept / n), accuracy: r3(right / n), usdPer1000: r3((cheapCostEach + (1 - kept / n) * modelCost) * 1000) } : null;
    };
    const kevCostEach = d.engines.kev ? d.engines.kev.usdPer1000.perCoreHour / 1000 : 0;
    m.cascades = { kevThenModel: kCal.length ? cascade(km, kCal, kevCostEach) : null, ruleThenModel: rCal.length ? cascade(rm, rCal, 0) : null, modelOnly: { accuracy: accOn(mm), usdPer1000: m.usdPer1000 } };
    d.engines.model = m;
  }
  // Paired Kev vs rule on the full evaluation half
  if (kEval.length && rEval.length) d.kevVsRule = mcnemar(new Map(kEval.map(r => [r.meta.itemId, r])), new Map(rEval.map(r => [r.meta.itemId, r])));
  // Order sensitivity and packing
  const perm = readJsonl(rawFile('permute', ds));
  const pm = perm.filter(r => r.kind === 'permute'), pk = perm.filter(r => r.kind === 'packing');
  if (pm.length) d.permutation = { items: pm.length, nPerm: pm[0].choices.length, flipRate: r3(pm.filter(r => !r.argmaxStable).length / pm.length), meanMaxSpread: r3(pm.reduce((s, r) => s + r.maxSpread, 0) / pm.length) };
  if (pk.length) d.packing = { items: pk.length, maxAbsDiff: Math.max(...pk.map(r => r.maxAbsDiff)) };
  // Failure examples: Kev's most confident wrong evaluation answers
  const byId = new Map(items.map(i => [i.id, i]));
  d.kevConfidentErrors = kEval.filter(r => r.chosen !== r.truth).sort((a, b) => b.confidence - a.confidence).slice(0, 3)
    .map(r => ({ itemId: r.meta.itemId, truth: r.truth, chosen: r.chosen, confidence: r3(r.confidence), meta: byId.get(r.meta.itemId)?.meta, state: JSON.stringify(byId.get(r.meta.itemId)?.state).slice(0, 360) }));
  summary.datasets[ds] = d;

  const e = d.engines, f = x => (x == null ? '–' : typeof x === 'number' ? x.toFixed(3) : x);
  const row = (name, m) => m ? `| ${ds} | ${name} | ${m.n} | ${f(m.accuracy)} [${f(m.ci95?.[0])}, ${f(m.ci95?.[1])}] | ${f(m.brier)} | ${f(m.ece)} | ${m.budget5?.eval ? `${f(m.budget5.calThreshold)} → ${f(m.budget5.eval.coverage)} @ ${f(m.budget5.eval.risk)}` : m.budget5?.inSample ? `in-sample ${f(m.budget5.coverage)}` : '–'} | ${m.budget10?.eval ? `${f(m.budget10.calThreshold)} → ${f(m.budget10.eval.coverage)} @ ${f(m.budget10.eval.risk)}` : m.budget10?.inSample ? `in-sample ${f(m.budget10.coverage)}` : '–'} | ${m.latency?.wall?.medianMs ?? '–'} | ${typeof m.usdPer1000 === 'object' ? `${f(m.usdPer1000.policyWallHour)} / ${f(m.usdPer1000.perCoreHour)}` : f(m.usdPer1000)} |` : null;
  md.push(...[row('kev', e.kev), row('rule', e.rule), row(HOSTED_MODEL, e.model)].filter(Boolean));
}

const outFile = path.join(ROOT, 'research/kev-20261007/probe-summary.json');
writeFileSync(outFile, JSON.stringify(summary, null, 1));
writeFileSync(path.join(RUN_DIR, 'tables.md'), ['| dataset | engine | n | accuracy [95% CI] | Brier | ECE | 5% budget: cal threshold → eval coverage @ eval risk | 10% budget | median ms | $ / 1000 |', '|---|---|---|---|---|---|---|---|---|---|', ...md].join('\n') + '\n');
console.log(readFileSync(path.join(RUN_DIR, 'tables.md'), 'utf8'));
