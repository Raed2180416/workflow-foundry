// Bundle a composed program for compose-runtime/2 (runtime2.mjs; research/blockers-20261021/MOVE2-COMP.md). $0.
// The frozen bundle.mjs (PREREG-COMP1) is imported, not edited: the program is bundled with the same runtime.mjs and
// loader.mjs, plus runtime2.mjs and the effect registry, and the composed solver is wrapped in the exactly-once
// envelope inside the sandbox. The static single-writer gate is checked beside the program's other problems:
// `gate: 'enforce'` (the default, as ATTACK.md Move 2 says: the gate refuses such a manifest) adds its problems to the
// program's, so a flagged program does not bundle; `gate: 'report'` runs it and only records the problems, and is for
// replaying programs built before the gate existed (fault-run2.mjs passes it explicitly; the battery rows say so).
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { RUNTIME_SOURCE, LOADER_SOURCE, programProblems } from './bundle.mjs';
import { singleWriterMessages, envRegistryProblems } from './runtime2.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const sha = s => createHash('sha256').update(s).digest('hex');
const stripExports = src => src.replace(/^export (const|function|class|async function) /gm, '$1 ');
export const RUNTIME2_SOURCE = readFileSync(path.join(here, 'runtime2.mjs'), 'utf8');
if (/^\s*import\s/m.test(RUNTIME2_SOURCE)) throw new Error('runtime2.mjs must import nothing (it is inlined into bundles)');
export const REGISTRY_PATH = path.join(here, 'effects.registry.json');
export const E8_REGISTRY = JSON.parse(readFileSync(REGISTRY_PATH, 'utf8'));
{ const p = envRegistryProblems(E8_REGISTRY); if (p.length) throw new Error(`effects.registry.json: ${p.join('; ')}`); }

/**
 * bundle2({ manifest, sources, mode }, { item, registry, gate }) → { source, digest, programDigest, problems, gate }:
 * the solver.mjs text (runtime + loader + runtime2 + program) that sandbox-arm.mjs runs.
 */
export function bundle2({ manifest, sources, mode = 'strict' }, { item = null, registry = E8_REGISTRY, gate = 'enforce', envelopeOptions = {} } = {}) {
  if (!['report', 'enforce'].includes(gate)) throw new Error(`gate must be report or enforce: ${gate}`);
  const regProblems = envRegistryProblems(registry);
  if (regProblems.length) throw new Error(`registry: ${regProblems.join('; ')}`);
  const gateProblems = manifest ? singleWriterMessages(manifest, registry) : [];
  const problems = [...programProblems({ manifest, sources }, { item }), ...(gate === 'enforce' ? gateProblems : [])];
  const used = {};
  for (const d of [manifest?.parent, ...Object.values(manifest?.modules ?? {})]) if (d?.file && typeof sources[d.file] === 'string') used[d.file] = sources[d.file];
  const source = `// Composed solver bundle, compose-runtime/2 (experiments/compose/bundle2.mjs). Generated by the harness; do not edit.
import vm from 'node:vm';
const MANIFEST = ${JSON.stringify(manifest)};
const SOURCES = ${JSON.stringify(used)};
const MODE = ${JSON.stringify(mode)};
const REGISTRY = ${JSON.stringify(registry)};
const ENVELOPE_OPTIONS = ${JSON.stringify(envelopeOptions)};
// ---- runtime.mjs ----
${stripExports(RUNTIME_SOURCE)}
// ---- loader.mjs ----
${stripExports(LOADER_SOURCE)}
// ---- runtime2.mjs ----
${stripExports(RUNTIME2_SOURCE)}
// ---- entry ----
export function createSolver() {
  const prog = loadProgram({ vm, manifest: MANIFEST, sources: SOURCES });
  if (prog.problems.length || !prog.parent) {
    const why = prog.problems.join('; ').slice(0, 1500) || 'no parent';
    return { id: 'composed', tick() { throw new Error('the composed program does not load: ' + why); } };
  }
  const solver = createComposedSolver({ manifest: MANIFEST, parent: prog.parent, modules: prog.modules, kindsOf: kindsOfE8, mode: MODE, realm: prog.realm });
  return withEnvelope({ id: 'composed', tick: (input, ctx) => solver.tick(input, ctx) }, { registry: REGISTRY, id: 'composed+env2', ...ENVELOPE_OPTIONS });
}
`;
  return { source, digest: sha(source), programDigest: sha(JSON.stringify({ manifest, sources: used })), problems, gate: gateProblems };
}
