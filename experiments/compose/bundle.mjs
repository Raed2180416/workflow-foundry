// Bundle a composed program into one tick/1 solver.mjs for the sandbox arm (research/composition-20261021/HARNESS.md
// §2.3). $0. The builder writes composition.json, parent.mjs and modules/*.mjs; the HARNESS bundles them with its own
// runtime (runtime.mjs) and loader (loader.mjs). The builder never writes the solver.mjs that is graded, so the
// runtime's enforcement is not the builder's to skip. Host side, nothing of the program is executed here: sources are
// only parsed (vm.Script compiles without running).
import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { manifestProblems } from './runtime.mjs';
import { sourceProblems, scriptOf } from './loader.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const sha = s => createHash('sha256').update(s).digest('hex');
const stripExports = src => src.replace(/^export (const|function|class|async function) /gm, '$1 ');
export const RUNTIME_SOURCE = readFileSync(path.join(here, 'runtime.mjs'), 'utf8');
export const LOADER_SOURCE = readFileSync(path.join(here, 'loader.mjs'), 'utf8');
for (const [n, s] of [['runtime.mjs', RUNTIME_SOURCE], ['loader.mjs', LOADER_SOURCE]]) if (/^\s*import\s/m.test(s)) throw new Error(`${n} must import nothing (it is inlined into bundles)`);

/** The item's effect ops and task kinds, for manifest checks. */
export function itemVocabulary(item) {
  const ops = Object.keys(item.schemas?.effects ?? {});
  const taskKinds = Object.keys(item.schemas?.humanTasks ?? item.binding?.schemas?.humanTasks ?? {});
  return { ops, taskKinds };
}

/** Read a program from a directory: composition.json and the files it names (nothing else). */
export function readProgram(dir) {
  const mf = path.join(dir, 'composition.json');
  if (!existsSync(mf)) return { manifest: null, sources: {}, problems: ['composition.json is missing'] };
  let manifest;
  try { manifest = JSON.parse(readFileSync(mf, 'utf8')); } catch (e) { return { manifest: null, sources: {}, problems: [`composition.json: ${String(e.message).slice(0, 200)}`] }; }
  const sources = {}, problems = [];
  const files = [manifest?.parent?.file, ...Object.values(manifest?.modules ?? {}).map(m => m?.file)].filter(f => typeof f === 'string');
  for (const f of files) {
    const p = path.resolve(dir, f);
    if (!p.startsWith(path.resolve(dir) + path.sep)) { problems.push(`${f}: outside the program directory`); continue; }
    if (!existsSync(p)) { problems.push(`${f}: missing`); continue; }
    sources[f] = readFileSync(p, 'utf8');
  }
  return { manifest, sources, problems };
}

/** Every problem the harness can find without running the program: manifest, static scan, syntax. */
export function programProblems({ manifest, sources }, { item = null } = {}) {
  const voc = item ? itemVocabulary(item) : {};
  const out = manifestProblems(manifest, voc);
  if (out.length) return out;
  for (const [who, d] of [['parent', manifest.parent], ...Object.entries(manifest.modules)]) {
    const src = sources[d.file];
    if (typeof src !== 'string') { out.push(`${who}: ${d.file} is missing`); continue; }
    const sp = sourceProblems(src);
    if (sp.length) { out.push(...sp.map(p => `${d.file}: ${p}`)); continue; }
    try { new vm.Script(scriptOf(src), { filename: d.file }); } catch (e) { out.push(`${d.file}: syntax: ${String(e.message).slice(0, 200)}`); }
  }
  return out;
}

/**
 * bundle({ manifest, sources, mode }) → { source, digest, problems }: the solver.mjs text (runtime + loader + program)
 * that sandbox-arm.mjs runs. A program with problems still bundles (it then fails at run time, visibly, as arm errors).
 */
export function bundle({ manifest, sources, mode = 'strict' }, { item = null } = {}) {
  const problems = programProblems({ manifest, sources }, { item });
  const used = {};
  for (const d of [manifest?.parent, ...Object.values(manifest?.modules ?? {})]) if (d?.file && typeof sources[d.file] === 'string') used[d.file] = sources[d.file];
  const source = `// Composed solver bundle (experiments/compose/bundle.mjs). Generated by the harness; do not edit.
import vm from 'node:vm';
const MANIFEST = ${JSON.stringify(manifest)};
const SOURCES = ${JSON.stringify(used)};
const MODE = ${JSON.stringify(mode)};
// ---- runtime.mjs ----
${stripExports(RUNTIME_SOURCE)}
// ---- loader.mjs ----
${stripExports(LOADER_SOURCE)}
// ---- entry ----
export function createSolver() {
  const prog = loadProgram({ vm, manifest: MANIFEST, sources: SOURCES });
  if (prog.problems.length || !prog.parent) {
    const why = prog.problems.join('; ').slice(0, 1500) || 'no parent';
    return { id: 'composed', tick() { throw new Error('the composed program does not load: ' + why); } };
  }
  const solver = createComposedSolver({ manifest: MANIFEST, parent: prog.parent, modules: prog.modules, kindsOf: kindsOfE8, mode: MODE, realm: prog.realm });
  return { id: 'composed', tick: (input, ctx) => solver.tick(input, ctx) };
}
`;
  return { source, digest: sha(source), programDigest: sha(JSON.stringify({ manifest, sources: used })), problems };
}
