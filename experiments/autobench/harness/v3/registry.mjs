// harness/v3 effect registry (ATTACK §6 Move 2): every outbound effect is keyed by ENTITY identity, never by the
// caller's trigger id, so a second write of the same effect is a no-op by algebra (exactly-once as a platform property).
//
//   routes(effects)              route matchers for every operation of the effect table (effects.json)
//   callFacts(call, routes)      the facts of one tool call: route, op, effect, channel kind, recipients, channels, text,
//                                record ids, containers, subject, name (null when the call is not an api_fetch or does not
//                                decode)
//   isWrite(facts)               a call that changes the world (send, create, update, delete, or an unclassified non-GET)
//   identityOf(facts)            the entity key of a planned effect
//   identityOfCreated(change)    the entity key of a created record in a world diff (the same key space, for audits)
//   createRegistry()             {key(facts), seen(key), record(key, meta), entries}
//
// effects.json is a byte-identical copy of experiments/autobench/harness/v2/effects.json (branch
// worktree-wf_3674d3bc-0a7-12 @ a65a3aeb, sha256 9883ddcdf214c6b9...; generated by v2 build-effects.mjs from the corpus
// tool schemas at corpus commit 4a8e1061), copied so the frozen A1-C v2 files stay untouched. The MIME decoding and the
// route matching are ported from v2 tool-gated.mjs / gate.mjs (new code, same semantics).
// Generic by construction (PREREG-AB-v1 H7/H8): no task names, grader strings or hidden assertions. Call arguments are
// untrusted data; nothing here executes them.
