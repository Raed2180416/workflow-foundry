const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const EMAIL = /[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g;
export const emailsIn = s => [...new Set((String(s ?? '').toLowerCase().match(EMAIL) ?? []))];
export const normText = s => String(s ?? '').toLowerCase().normalize('NFKC').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[–—]/g, '-').replace(/\s+/g, ' ').trim();
const h = s => createHash('sha256').update(normText(s)).digest('hex').slice(0, 16);

/** Route matchers: method, host (the app's base host, or one sharing its last two labels), the path tail (the operation
 *  path minus 0-2 leading segments, params as one segment), and the body constants that select shared paths. */
export function routes(effects = EFFECTS) {
  const out = [];
  for (const r of effects.rows) {
    const base = effects.apps?.[r.app]?.baseUrl ?? null;
    let host = null;
    try { host = new URL(String(base).replace(/\{[^}]+\}/g, 'x')).host; } catch { /* no base */ }
    const labels = String(host ?? '').split('.').filter(Boolean);
    const baseHost = String(base ?? '').replace(/^https?:\/\//, '').split('/')[0];
    const hostRe = baseHost ? `^(?:${esc(baseHost).replace(/\\\{[^}]*\\\}/g, '[^.]+')}|(?:[^.]+\\.)*${esc(labels.slice(-2).join('.'))})$` : '.*';
    const segs = r.path.split('/').filter(Boolean);
    for (let k = 0; k <= Math.min(2, segs.length - 1); k++) {
      const tail = segs.slice(k);
      const lit = tail.filter(s => !/\{[^}]+\}/.test(s)).join('/').length;
      if (!lit) continue;
      const names = tail.flatMap(s => [...s.matchAll(/\{([^}]+)\}/g)].map(m => m[1]));
      out.push({ op: r.op, app: r.app, appKey: r.appKey, channel: r.channel, method: r.method, effect: r.effect, kind: r.kind, host: hostRe,
        tail: `(?:^|/)${tail.map(s => esc(s).replace(/\\\{[^}]*\\\}/g, '([^/]+)')).join('/')}$`, params: names, lit,
        ...(r.bodyIs ? { bodyIs: r.bodyIs } : {}), ...(r.bodyIsNot ? { bodyIsNot: r.bodyIsNot } : {}) });
    }
  }
  return out;
}
const ROUTES = routes();

const bodyHas = (body, want) => Object.entries(want ?? {}).every(([k, v]) => body && typeof body === 'object' && String(body[k]) === String(v));
/** The most specific route a method + URL (and, where operations share a path, the body) reach; with its path params. */
export function routeOf(method, url, rs = ROUTES, body = null) {
  let u;
  try { u = new URL(String(url)); } catch { return null; }
  let p;
  try { p = decodeURIComponent(u.pathname); } catch { p = u.pathname; }
  let best = null, bestParams = null;
  for (const r of rs) {
    if (String(method).toUpperCase() !== r.method) continue;
    if (!new RegExp(r.host, 'i').test(u.host)) continue;
    const m = new RegExp(r.tail).exec(p);
    if (!m) continue;
    if (r.bodyIs && !bodyHas(body, r.bodyIs)) continue;
    if (r.bodyIsNot && bodyHas(body, r.bodyIsNot)) continue;
    if (!best || r.lit > best.lit) { best = r; bestParams = Object.fromEntries(r.params.map((n, i) => [n, m[i + 1]])); }
  }
  return best ? { ...best, values: bestParams } : null;
}

// ---- Gmail raw MIME (ported from v2 tool-gated.mjs)
const qpDecode = s => Buffer.from(String(s).replace(/=\r?\n/g, '').replace(/=([0-9A-Fa-f]{2})/g, (_, x) => String.fromCharCode(parseInt(x, 16))), 'latin1').toString('utf8');
const decodeWords = s => String(s ?? '').replace(/=\?([^?]+)\?([BbQq])\?([^?]*)\?=/g, (_, cs, enc, t) => (/^b$/i.test(enc) ? Buffer.from(t, 'base64').toString('utf8') : qpDecode(t.replace(/_/g, ' '))));
function parseHeaders(block) {
  const out = {};
  for (const line of String(block).replace(/\r?\n[ \t]+/g, ' ').split(/\r?\n/)) { const m = /^([\w-]+):\s*(.*)$/.exec(line); if (m) out[m[1].toLowerCase()] = (out[m[1].toLowerCase()] ? `${out[m[1].toLowerCase()]}, ` : '') + m[2]; }
  return out;
}
function decodePart(headers, body) {
  const cte = String(headers['content-transfer-encoding'] ?? '').toLowerCase().trim();
  if (cte === 'base64') return Buffer.from(String(body).replace(/\s+/g, ''), 'base64').toString('utf8');
  if (cte === 'quoted-printable') return qpDecode(body);
  return String(body);
}
function mimeText(headers, body, depth = 0) {
  const ct = String(headers['content-type'] ?? 'text/plain');
  const b = /boundary="?([^";]+)"?/i.exec(ct)?.[1];
  if (/^multipart\//i.test(ct) && b && depth < 4) {
    const parts = String(body).split(new RegExp(`--${esc(b)}(?:--)?\\s*`)).filter(x => x.trim());
    const texts = parts.map(x => { const k = x.search(/\r?\n\r?\n/); if (k < 0) return null; const ph = parseHeaders(x.slice(0, k)); return { ct: String(ph['content-type'] ?? 'text/plain'), text: mimeText(ph, x.slice(k).replace(/^\r?\n\r?\n/, ''), depth + 1) }; }).filter(Boolean);
    const plain = texts.filter(t => /text\/plain|multipart/i.test(t.ct));
    return (plain.length ? plain : texts).map(t => t.text).join('\n');
  }
  return decodePart(headers, body);
}
/** A Gmail `raw` message (base64url MIME) -> {to[], cc[], bcc[], subject, text} or null. */
export function decodeRaw(raw) {
  if (typeof raw !== 'string' || !raw.trim() || !/^[A-Za-z0-9_\-+/=\s]+$/.test(raw)) return null;
  let s;
  try { s = Buffer.from(raw.replace(/\s+/g, ''), 'base64url').toString('utf8'); } catch { return null; }
  const k = s.search(/\r?\n\r?\n/);
  if (k < 0 || s.includes('�')) return null;
  const hd = parseHeaders(s.slice(0, k));
  if (!hd.to && !hd.subject && !hd['content-type']) return null;
  let text;
  try { text = mimeText(hd, s.slice(k).replace(/^\r?\n\r?\n/, '')); } catch { return null; }
  return { to: emailsIn(hd.to), cc: emailsIn(hd.cc), bcc: emailsIn(hd.bcc), subject: decodeWords(hd.subject ?? ''), text };
}

const parseMaybe = s => { if (s === null || s === undefined || s === '') return null; if (typeof s === 'object') return s; try { return JSON.parse(s); } catch { return undefined; } };
// leaves as [key, value, parent key, depth]: the parent tells an entity's own name from a nested reference's name
const leaves = (v, out = [], key = null, parent = null, depth = 0) => {
  if (v === null || v === undefined) return out;
  if (Array.isArray(v)) { v.forEach(x => leaves(x, out, key, parent, depth)); return out; }
  if (typeof v === 'object') { for (const [k, x] of Object.entries(v)) leaves(x, out, k, key, depth + 1); return out; }
  out.push([key, String(v), parent, depth]);
  return out;
};
const NAME_KEY = /^(name|title|summary|subject|dealname|topic|label|card_?name|task_?name|issue_?title|page_?title)$/i;
// Identity v2 (Δ* v1 replay, in-sample dev60, disclosed): a name is the ENTITY's name only at the top of the body or
// directly under a wrapper object; the name of a nested reference (an issue type, a project, a status, a priority) is an
// attribute, not an identity. v1 took the first name-like leaf anywhere, so every new issue of one type shared a key.
const WRAPPER = /^(fields|properties|data|record|attributes|resource|item|values|object)$/i;
const entityLevel = (parent, depth) => depth <= 1 || (depth === 2 && WRAPPER.test(parent ?? ''));
// structured attributes of a create (short scalars at entity level, other than the name): two creates with one name but
// different attributes (another customer, another start time) are two effects; long free text is not identity (a
// re-send with reworded prose is still the same effect)
const SHORT = v => v.length <= 80 && !/\n/.test(v);
const ID_KEY = /(^id$|_id$|Id$|^ids?$|^parent$|^record$|^ticket$|^conversation$|^card$|^task$|^issue$|^page$|^board$|^list$|^project$|^workspace$|^spreadsheet$)/;
const CALLER_KEY = /^(idempotency_?key|request_?id|client_?request_?id|nonce|trigger_?id|dedupe_?key|correlation_?id)$/i;

/** The facts of one tool call, or null (not api_fetch, undecodable body, or no route). */
export function callFacts(call, rs = ROUTES) {
  if (!call || call.name !== 'api_fetch') return null;
  const args = parseMaybe(call.arguments);
  if (!args || typeof args !== 'object') return null;
  let body = parseMaybe(args.body);
  if (body === undefined) body = typeof args.body === 'string' ? { text: args.body } : null;
  const params = parseMaybe(args.params) ?? null;
  const method = String(args.method ?? 'GET').toUpperCase();
  const route = routeOf(method, args.url, rs, body);
  const recipients = new Set(), channels = new Set(), texts = [], ids = new Set(), attrs = [];
  let subject = '', name = '', nameV1 = '';
  for (const obj of [body, params]) {
    if (!obj || typeof obj !== 'object') continue;
    if (typeof obj.raw === 'string') {
      const m = decodeRaw(obj.raw);
      if (!m) return null;
      [...m.to, ...m.cc, ...m.bcc].forEach(e => recipients.add(e));
      subject = subject || m.subject;
      texts.push(m.subject, m.text);
    }
    for (const [k, v, parent, depth] of leaves(obj)) {
      if (k === 'raw' || CALLER_KEY.test(k ?? '')) continue;
      if (/^(to|cc|bcc|recipients?|email|emailaddress|address|phone|number|to_number|signer_email)$/i.test(k ?? '')) emailsIn(v).forEach(e => recipients.add(e));
      if (/^(to|to_number|phone|number)$/i.test(k ?? '') && /^\+?\d[\d\s()-]{6,}$/.test(v)) recipients.add(v.replace(/[\s()-]/g, ''));
      if (/^(channel|channel_id|channelid|conversation)$/i.test(k ?? '')) channels.add(String(v).replace(/^#/, ''));
      if (/^subject$/i.test(k ?? '') && !subject) subject = v;
      if (NAME_KEY.test(k ?? '') && !nameV1) nameV1 = v;
      const own = entityLevel(parent, depth);
      if (NAME_KEY.test(k ?? '') && own && !name) name = v;
      else if (SHORT(v) && (own || depth <= 3)) attrs.push(`${String(k ?? '').toLowerCase()}=${normText(v)}`);
      if (ID_KEY.test(k ?? '') && v.length <= 80) ids.add(v);
      texts.push(v);
    }
  }
  const values = route?.values ?? {};
  for (const [k, v] of Object.entries(values)) if (!/^(userId|version|companyDomain|subdomain|instance)$/i.test(k) && v && v !== 'me') ids.add(decodeURIComponent(v));
  return { route, method, url: String(args.url ?? ''), app: route?.app ?? null, op: route?.op ?? null, effect: route?.effect ?? (method === 'GET' ? 'get' : 'other'), channelKind: route?.channel ?? null,
    recipients: [...recipients], channels: [...channels], ids: [...ids], subject: String(subject ?? ''), name: String(name ?? ''), nameV1: String(nameV1 ?? ''), attrs: attrs.sort(), text: texts.join('\n'), body };
}

/** Does the call change the world? */
export const isWrite = f => Boolean(f) && (['send', 'create', 'update', 'delete'].includes(f.effect) || (f.method !== 'GET' && f.effect === 'other' && !/query|search|graphql/i.test(f.url)));

/** The entity key of a planned effect (identity v2). Never the caller's trigger id: caller-chosen keys are ignored.
 *  A create is keyed by (app, op, ids, entity-level name, structured attributes); without a name, by its content. */
export function identityOf(f) {
  if (!f) return null;
  if (f.effect === 'create' && !['email', 'chat', 'dm', 'sms', 'social', 'reply', 'note', 'esign'].includes(f.channelKind)) {
    const ids = [...f.ids].sort().join(',');
    return f.name ? `create|${f.app}|${f.op}|${ids}|${normText(f.name)}|${h((f.attrs ?? []).join('|'))}` : `create|${f.app}|${f.op}|${ids}|${h(f.text)}`;
  }
  return identityOfV1(f);
}

/** Identity v1, as first replayed (kept for the comparison replay): the first name-like leaf anywhere names a create. */
export function identityOfV1(f) {
  if (!f) return null;
  const rec = [...f.recipients].sort().join(',');
  const ch = [...f.channels].map(normText).sort().join(',');
  const ids = [...f.ids].sort().join(',');
  if (f.channelKind === 'email') return `email|${rec}|${normText(f.subject)}`;
  if (['chat', 'dm', 'sms', 'social'].includes(f.channelKind)) return `${f.channelKind}|${f.app}|${ch || rec}|${h(f.text)}`;
  if (['reply', 'note'].includes(f.channelKind)) return `${f.channelKind}|${f.app}|${ids}|${h(f.text)}`;
  if (f.channelKind === 'esign') return `esign|${f.app}|${rec}|${normText(f.subject || f.name)}`;
  switch (f.effect) {
    case 'create': { const nm = f.nameV1 ?? f.name; return `create|${f.app}|${f.op}|${ids}|${nm ? normText(nm) : h(f.text)}`; }
    case 'update': return `update|${f.app}|${f.op}|${ids}|${h(f.text)}`;
    case 'delete': return `delete|${f.app}|${f.op}|${ids}`;
    default: { let host = f.app; if (!host) { try { host = new URL(f.url).host; } catch { host = `?${h(f.url)}`; } } return `other|${host}|${f.op ?? f.url}|${h(f.text)}`; }
  }
}

/** The same key space for a created record of a world diff ({app, coll, record}), for duplicate audits. */
export function identityOfCreated(c) {
  const r = c.record ?? {};
  const rec = emailsIn(JSON.stringify([r.to, r.cc, r.bcc, r.recipients, r.to_number].filter(Boolean))).sort().join(',');
  if (c.app === 'gmail' && c.coll === 'messages') return `email|${rec}|${normText(r.subject)}`;
  if (c.app === 'slack' && c.coll === 'messages') return `chat|slack|${normText(r.channel_id ?? r.channel)}|${h(r.text)}`;
  if (c.app === 'google_sheets' && c.coll === 'rows') return `create|google_sheets|row|${r.spreadsheet_id}/${r.worksheet_id}|${h(JSON.stringify(Object.values(r.cells ?? {})))}`;
  if (String(c.coll).startsWith('actions')) return `create|${c.app}|${c.coll}|${h(JSON.stringify(r.params ?? r))}`;
  const name = r.name ?? r.title ?? r.summary ?? r.subject ?? r.dealname ?? null;
  return `create|${c.app}|${c.coll}|${name ? normText(name) : h(JSON.stringify(r))}`;
}

/** A registry of committed effects: the gate consults it before every write and records every admitted write. */
export function createRegistry() {
  const entries = new Map();
  return {
    entries,
    seen: key => entries.has(key),
    record: (key, meta = {}) => { if (!entries.has(key)) entries.set(key, { first: meta, count: 0 }); entries.get(key).count++; return entries.get(key); },
    // a write that failed did not happen: its key is released (one record per committed effect)
    forget: key => { const e = entries.get(key); if (!e) return; e.count--; if (e.count <= 0) entries.delete(key); },
  };
}
