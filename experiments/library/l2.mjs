// l2.mjs: the L2 retrieval harness, code arms only (LIBRARY-TESTS L2 arms A1, A2; T9; BUILD-ORDER step 5). $0: no model,
// no Jev, no embedding (arm A3 bge-small is not built: no local embedder in the repo). Corpus text is untrusted data: it is
// read only as a BM25 query and for shape features, and nothing here prints it.
//
// Task sets:
//   corpus      every item of census revision 1 that is not refused (1,510): the task is the item's title + written summary
//               (research/corpus-20261006/items.jsonl `description.text`); gold = the census `needs` that are L1 patterns
//               (out/pattern-census-items.jsonl; plumbing such as P01's support-only idiom is not in `needs`). Items whose
//               needs are L0-only have no gold and are counted, not scored.
//   stripped    the same with structural words removed by the fixed list STRUCTURAL below (LIBRARY-TESTS L2: the
//               summaries were written by an agent that read the workflow, so they over-state structure).
//   wbed        W-bed R1-R3 fixture tasks (dev seeds 373-378, difficulty 3): the task prompt and inputs (shape features
//               see the inputs); gold = the patterns BUILD-ORDER §4 assigns to the rung (no reference workflow, arm c, is
//               written yet, so this is the design's declared need, not an extracted one).
// Arms: A1 BM25 over the L1 cards; A2 the code ranker (retrieve.mjs, §4.3); FLOOR a fixed popularity order (L1 patterns by
// census support, most first) — it leaks the corpus gold's marginal, so it is a floor to read A1/A2 against, not an arm.
// Metrics: recall@3, @5, @20, precision@5, mean reciprocal rank of the first gold pattern; means with a platform-clustered
// bootstrap 95% CI (B = 4,000; for W-bed the cluster is the rung). Nothing is fitted, so leave-platform-out does not apply.
// Falsifier (L2): A2 recall@5 < 0.7 on the W-bed tasks.
import { readFileSync } from 'node:fs';
import { loadL1 } from './cards.mjs';
import { l1Context, armA1, armA2, itemMetrics, clusterMean } from './retrieve.mjs';

const REPO = new URL('../../', import.meta.url);
export const CORPUS_ITEMS = new URL('research/corpus-20261006/items.jsonl', REPO);
export const CENSUS_ITEMS = new URL('research/jit-20261008/design/library/out/pattern-census-items.jsonl', REPO);
export const WBED_GOLD = Object.freeze({   // BUILD-ORDER §4 "patterns (tier)" column
  'wbed-r1': ['P01', 'P03', 'P13', 'P16', 'P17', 'P20'],
  'wbed-r2': ['P07', 'P08', 'P09', 'P05'],
  'wbed-r3': ['P12', 'P14', 'P15', 'P17'],
});
export const WBED_SEEDS = Object.freeze([373, 374, 375, 376, 377, 378]);
// Structural words removed in the stripped variant (fixed before any number was computed; lower case, whole words).
export const STRUCTURAL = Object.freeze(('node nodes edge edges trigger triggers triggered loop loops looping condition conditions conditional '
  + 'branch branches branching router routes route routing switch merge merges map maps mapping parallel fan fanout scatter gather '
  + 'wait waits delay retry retries error errors handler fallback webhook webhooks schedule scheduled cron poll polling event events '
  + 'subworkflow subworkflows sub workflow workflows pipeline pipelines step steps stage stages task tasks dag graph flow flows template '
  + 'model models llm agent agents tool tools code transform transforms action actions human approval approve batch batches '
  + 'iterate iteration each foreach while until stream streaming session state memory compose composite call calls invoke').split(' '));
export const stripStructural = text => String(text).replace(/\b\d+\b/g, ' ').split(/(\W+)/).filter(w => !STRUCTURAL.includes(w.toLowerCase())).join('').replace(/\s+/g, ' ').trim();

const readJsonl = url => readFileSync(url, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l));

// The corpus task set: [{id, cluster (platform), text, gold}] plus the count of L0-only items.
export function corpusTasks({ variant = 'corpus' } = {}) {
  const census = new Map(readJsonl(CENSUS_ITEMS).map(r => [r.id, r]));
  const out = [];
  let l0only = 0, refused = 0;
  for (const it of readJsonl(CORPUS_ITEMS)) {
    const c = census.get(it.id);
    if (!c) throw new Error(`l2: corpus item ${it.id} is not in the census`);
    if (c.status === 'refused') { refused++; continue; }
    const gold = Object.keys(c.needs ?? {}).filter(k => /^P\d\d$/.test(k)).sort();
    if (!gold.length) { l0only++; continue; }
    const raw = `${it.title ?? ''}\n${it.description?.text ?? ''}`;
    out.push({ id: it.id, cluster: c.plat, text: variant === 'stripped' ? stripStructural(raw) : raw, gold });
  }
  return { tasks: out, l0only, refused };
}

// The W-bed task set (generated by the beds; the oracle is never imported or called).
export async function wbedTasks({ seeds = WBED_SEEDS, difficulty = 3 } = {}) {
  const out = [];
  for (const [family, gold] of Object.entries(WBED_GOLD)) {
    const m = await import(new URL(`beds/wbed/${family.slice(5)}/index.mjs`, REPO).href);
    for (const seed of seeds) {
      const t = m.generate({ seed, split: 'dev', difficulty });
      out.push({ id: t.id, cluster: family, task: { prompt: t.prompt, inputs: t.inputs }, gold });
    }
  }
  return out;
}

// Run the arms over a task set. Returns {arms: {A1, A2, FLOOR: {metric: {mean, lo, hi}}}, perItem?, n}.
export function scoreArms(tasks, { l1 = loadL1(), B = 4000, keepItems = false } = {}) {
  const ctx = l1Context(l1);
  const floor = [...l1].sort((a, b) => (b.support?.items ?? 0) - (a.support?.items ?? 0) || (a.id < b.id ? -1 : 1)).map(e => e.id);
  const ranked = {
    A1: t => armA1(t.text ?? t.task.prompt, ctx.engine),
    A2: t => armA2(t.task ? { task: t.task } : { text: t.text }, ctx),
    FLOOR: () => floor,
  };
  const arms = {}, perItem = {};
  for (const [arm, rank] of Object.entries(ranked)) {
    const rows = tasks.map(t => { const r = rank(t); return { id: t.id, cluster: t.cluster, n: r.length, top5: r.slice(0, 5), m: itemMetrics(r, t.gold) }; });
    arms[arm] = Object.fromEntries(['recall@3', 'recall@5', 'recall@20', 'precision@5', 'rr'].map(k => [k === 'rr' ? 'mrr' : k, clusterMean(rows, k, { B })]));
    arms[arm].meanListLength = Math.round(rows.reduce((a, r) => a + r.n, 0) / Math.max(1, rows.length) * 100) / 100;
    if (keepItems) perItem[arm] = rows;
  }
  return { n: tasks.length, clusters: new Set(tasks.map(t => t.cluster)).size, arms, ...(keepItems ? { perItem } : {}) };
}

// The whole harness: the three task sets and the falsifier reading.
export async function runL2({ B = 4000 } = {}) {
  const l1 = loadL1();
  const corpus = corpusTasks(), stripped = corpusTasks({ variant: 'stripped' }), wbed = await wbedTasks();
  const res = {
    schema: 'library-l2-code-arms/1', generatedBy: 'experiments/library/tools/l2-harness.mjs', costUsd: 0, modelCalls: 0, jevCalls: 0,
    census: 'revision 1 (out/pattern-census-items.jsonl), a candidate generator; gold = its L1 needs',
    corpus: { ...scoreArms(corpus.tasks, { l1, B }), l0only: corpus.l0only, refused: corpus.refused },
    stripped: { ...scoreArms(stripped.tasks, { l1, B }), l0only: stripped.l0only, refused: stripped.refused },
    wbed: { ...scoreArms(wbed, { l1, B }), gold: 'BUILD-ORDER §4 (declared, no reference workflow yet)', seeds: WBED_SEEDS },
  };
  const r5 = res.wbed.arms.A2['recall@5'].mean;
  res.falsifier = { rule: 'A2 recall@5 < 0.7 on W-bed tasks', a2Recall5Wbed: r5, met: r5 < 0.7 };
  return res;
}
