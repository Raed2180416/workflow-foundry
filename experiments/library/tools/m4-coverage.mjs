// Run the M4 enumeration coverage measurement (m4.mjs over enumerate.mjs) and write it beside the other library outputs
// ($0; no model, Jev or network call):
//   research/jit-20261008/design/library/out/M4-enumeration.json   every number, per task
//   research/jit-20261008/design/library/out/M4-enumeration.md     the tables and the decision
//
//   node experiments/library/tools/m4-coverage.mjs [--dry]
import { writeFileSync } from 'node:fs';
import { measureM4 } from '../m4.mjs';

const dry = process.argv.includes('--dry');
const OUT = new URL('../../../research/jit-20261008/design/library/out/', import.meta.url);

const r = await measureM4();
const pct = x => `${Math.round(x * 1000) / 10}%`;
const dec = d => `${d.kill ? '**KILL**' : 'pass'}: ${d.over} of ${d.tasks} tasks over 100, coverage ${d.covered}/${d.tasks} (${pct(d.coverage)})`;
const fx = r.rows.filter(x => x.set === 'fixtures'), wb = r.rows.filter(x => x.set === 'wbed');
const rung = k => wb.find(x => x.rung === k);
const md = [
  '# M4 enumeration coverage (ATTACK-20261014 §3 M4; PROOF-LEDGER K6)', '',
  `*Generated by \`experiments/library/tools/m4-coverage.mjs\` at $0 (no model, Jev or network call). Enumerator \`experiments/library/enumerate.mjs\` `
  + `(sha256 ${r.files.enumerate.slice(0, 12)}), measurement \`m4.mjs\` (${r.files.m4.slice(0, 12)}), gold \`fixtures/enumerate-gold.mjs\` (${r.files.gold.slice(0, 12)}, `
  + 'frozen before the enumerator existed). Development evidence on dev fixtures only; no held-out claim.*', '',
  `**Rule:** ${r.rule.text}; read on the \`temporal\` layer (types + declared temporal constraints) at depth ≤ ${r.rule.maxDepth}.`, '',
  '| task set | decision |', '|---|---|',
  `| all 33 tasks (15 card fixtures + 18 W-bed) | ${dec(r.decision.all)} |`,
  `| 18 distinct type problems (15 + R1, R2, R3) | ${dec(r.decision.distinctProblems)} |`,
  `| card fixtures (15) | ${dec(r.decision.fixtures)} |`,
  `| W-bed R1–R3 × seeds 373–378 (18) | ${dec(r.decision.wbed)} |`, '',
  '## Candidates per task (depth ≤ 4; by depth 1 / 2 / 3 / 4 on the rule\'s layer)', '',
  '| task | input list sites | raw | typed | temporal (rule) | by depth | covered | covering | first gold depth | gold rank (code order) |', '|---|---|---|---|---|---|---|---|---|---|',
  ...[...fx, ...['r1', 'r2', 'r3'].map(rung)].map(x => `| ${x.set === 'wbed' ? `W-bed ${x.rung.toUpperCase()} (each of 6 seeds)` : x.id} | ${Number.isFinite(x.inputListSites) ? x.inputListSites : '∞'} | ${x.layers.raw.total} | ${x.layers.typed.total} | ${x.total} | ${x.layers.temporal.byDepth.join(' / ')} | ${x.covered ? 'yes' : 'no'} | ${x.covering.count} | ${x.covering.minDepth ?? '—'} | ${x.codeOrder.goldRank ?? '—'} |`),
  '',
  '## Sensitivities (diagnostic; not the rule)', '',
  '| setting | decision over 33 tasks |', '|---|---|',
  ...Object.entries(r.sensitivityDecisions).map(([k, d]) => `| ${{ distinct: 'a card at most once', s4Alphabet: 'alphabet = the S4 code ranker\'s shown set', depth3: 'depth ≤ 3', all: 'all three' }[k]} | ${dec(d)} |`),
  '',
  '## W-bed secondary golds', '',
  '| rung | covering candidates | examples | BUILD-ORDER §4 set (executable) | best single-candidate recall | full containment at depth ≤ 4 | step-6 scripted plan enumerated | TaskSpec vs inputs type |', '|---|---|---|---|---|---|---|---|',
  ...['r1', 'r2', 'r3'].map(k => { const x = rung(k); return `| ${k.toUpperCase()} | ${x.covering.count} | ${x.covering.examples.slice(0, 3).join(', ')} | ${x.declared.executable.join(' ')} | ${x.declared.bestHits}/${x.declared.executable.length} | ${x.declared.fullContainmentPossible ? 'yes' : 'no'} | ${x.scriptedPlanEnumerated ? 'yes' : 'no'} | ${x.inputCrossCheck.agrees ? 'agree' : 'DIFFER'} |`; }),
  '',
  '## Card interfaces (derived by code from card.json)', '',
  '| card | readers (slot: type) | list sites needed | output |', '|---|---|---|---|',
  ...r.cards.map(c => `| ${c.id} | ${c.readers.map(x => `${x.slot}: ${x.type}`).join(', ') || '— (any)'} | ${c.needsLists} | ${Array.isArray(c.out) ? `{${c.out.join(', ')}}` : c.out} |`),
  '',
  '## Temporal constraints (A before B when both occur)', '',
  ...r.temporal.map(t => `- \`${t.pair}\`: ${t.source}`), '',
];
if (dry) process.stdout.write(md.join('\n'));
else {
  writeFileSync(new URL('M4-enumeration.json', OUT), JSON.stringify(r, (k, v) => (v === Infinity ? null : v), 1) + '\n');
  writeFileSync(new URL('M4-enumeration.md', OUT), md.join('\n'));
  process.stdout.write(`wrote out/M4-enumeration.json and .md; kill: ${r.decision.all.kill} (${r.decision.all.reasons.join('; ')})\n`);
}
