// Run the L2 code arms (l2.mjs) and write the result beside the census outputs ($0; no model, Jev or network):
//   research/jit-20261008/design/library/out/L2-code-arms.json   every number, with platform-clustered 95% CIs
//   research/jit-20261008/design/library/out/L2-code-arms.md     the table
//
//   node experiments/library/tools/l2-harness.mjs [--B 4000] [--dry]
import { writeFileSync } from 'node:fs';
import { runL2 } from '../l2.mjs';

const args = process.argv.slice(2);
const B = Number(args[args.indexOf('--B') + 1]) || 4000, dry = args.includes('--dry');
const OUT = new URL('../../../research/jit-20261008/design/library/out/', import.meta.url);
const r = await runL2({ B });
const f = v => `${v.mean.toFixed(3)} (${v.lo.toFixed(3)}–${v.hi.toFixed(3)})`;
const table = (name, s) => [
  `### ${name} (n = ${s.n} tasks, ${s.clusters} clusters${s.l0only != null ? `; ${s.l0only} L0-only items not scored, ${s.refused} refused` : ''})`, '',
  '| arm | recall@3 | recall@5 | recall@20 | precision@5 | MRR | mean list |', '|---|---|---|---|---|---|---|',
  ...Object.entries(s.arms).map(([a, m]) => `| ${a} | ${f(m['recall@3'])} | ${f(m['recall@5'])} | ${f(m['recall@20'])} | ${f(m['precision@5'])} | ${f(m.mrr)} | ${m.meanListLength} |`), ''];
const md = [
  '# L2 retrieval, code arms (LIBRARY-TESTS L2 A1, A2; T9)', '',
  `*Generated by \`experiments/library/tools/l2-harness.mjs\` at $0 (no model, Jev or embedding call). Gold: ${r.census}. `
  + 'A1 = BM25 over the L1 cards; A2 = the code ranker of LIBRARY §4.3 (`experiments/library/retrieve.mjs`); FLOOR = L1 patterns in census-support order, '
  + 'which leaks the corpus gold\'s marginal and is a floor, not an arm. A3 (bge-small) is not built. 95% CIs: cluster bootstrap '
  + `(platform; for W-bed the rung), B = ${B}.*`, '',
  ...table('Corpus summaries', r.corpus), ...table('Corpus summaries, structural words stripped', r.stripped), ...table(`W-bed R1–R3 fixture tasks (dev seeds ${r.wbed.seeds.join(', ')}; gold ${r.wbed.gold})`, r.wbed),
  `**Falsifier (L2):** ${r.falsifier.rule}: A2 recall@5 on W-bed = ${r.falsifier.a2Recall5Wbed} → ${r.falsifier.met ? '**met** (code-first retrieval at k = 5 is not adequate on these tasks)' : 'not met'}.`, '',
];
if (dry) process.stdout.write(md.join('\n'));
else {
  writeFileSync(new URL('L2-code-arms.json', OUT), JSON.stringify(r, null, 1) + '\n');
  writeFileSync(new URL('L2-code-arms.md', OUT), md.join('\n'));
  process.stdout.write(`wrote out/L2-code-arms.json and .md; falsifier met: ${r.falsifier.met}\n`);
}
