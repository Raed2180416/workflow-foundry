// Run M4b, the M4 coverage measurement on the precise card type model (m4b.mjs over card-types.mjs), and write it beside
// the M4 outputs, which stay as they were ($0; no model, Jev or network call):
//   research/jit-20261008/design/library/out/M4b-enumeration.json   every number, per task
//   research/jit-20261008/design/library/out/M4b-enumeration.md     the tables and the decision
//
//   node experiments/library/tools/m4b-coverage.mjs [--dry]
import { writeFileSync } from 'node:fs';
import { measureM4b } from '../m4b.mjs';

const dry = process.argv.includes('--dry');
const OUT = new URL('../../../research/jit-20261008/design/library/out/', import.meta.url);

const r = await measureM4b();
const pct = x => `${Math.round(x * 1000) / 10}%`;
const dec = d => `${d.kill ? '**KILL**' : 'pass'}: ${d.over} of ${d.tasks} tasks over 100, coverage ${d.covered}/${d.tasks} (${pct(d.coverage)})`;
const fx = r.rows.filter(x => x.set === 'fixtures'), wb = r.rows.filter(x => x.set === 'wbed');
const rung = k => wb.find(x => x.rung === k);
const shown = [...fx, ...['r1', 'r2', 'r3'].map(rung)];
const label = x => (x.set === 'wbed' ? `W-bed ${x.rung.toUpperCase()} (each of 6 seeds)` : x.id);
const outText = o => (o.$param ? `${o.$param} (${o.check})` : o.$union ? o.$union.map(b => `{${Object.entries(b.properties).map(([k, v]) => `${k}${v.$param ? `: ${v.$param}` : v.type === 'null' ? ': null' : ''}`).join(', ')}}`).join(' or ') : JSON.stringify(o));
const cite = c => `${c.file.replace('experiments/library/', '')}:${c.line}`;
const P = r.precise;
const md = [
  '# M4b: M4 on the precise card type model (ATTACK-20261014 §3 M4; PROOF-LEDGER K6)', '',
  `*Generated by \`experiments/library/tools/m4b-coverage.mjs\` at $0 (no model, Jev or network call). Type model \`experiments/library/card-types.mjs\` `
  + `(sha256 ${r.files.cardTypes.slice(0, 12)}), measurement \`m4b.mjs\` (${r.files.m4b.slice(0, 12)}); M4's enumerator (${r.files.enumerate.slice(0, 12)}), task sets (\`m4.mjs\`, `
  + `${r.files.m4.slice(0, 12)}) and gold (${r.files.gold.slice(0, 12)}) are unchanged and reused. Development evidence on dev fixtures only; no held-out claim. `
  + 'M4\'s own outputs (`M4-enumeration.{json,md}`) are kept as they were.*', '',
  `**Rule (unchanged):** ${r.rule.text}; read on ${r.rule.layer}, at depth ≤ ${r.rule.maxDepth}.`, '',
  '| task set | M4b decision |', '|---|---|',
  `| all 33 tasks (15 card fixtures + 18 W-bed) | ${dec(r.decision.all)} |`,
  `| 18 distinct type problems (15 + R1, R2, R3) | ${dec(r.decision.distinctProblems)} |`,
  `| card fixtures (15) | ${dec(r.decision.fixtures)} |`,
  `| W-bed R1–R3 × seeds 373–378 (18) | ${dec(r.decision.wbed)} |`,
  `| M4, for comparison | ${dec(r.m4Decision)} |`, '',
  `Counts unchanged from M4 on ${r.unchanged} of ${r.rows.length} tasks.`, '',
  '## What the catch-all cards\' skeletons accept and produce', '',
  '| card | reads | input | output | type-preserving |', '|---|---|---|---|---|',
  ...Object.entries(P).map(([id, p]) => `| ${id} | ${[p.reads.task ? 'task' : null, p.reads.x ? 'x' : null].filter(Boolean).join(', ')} | ${p.readers.map(x => x.kind === 'path' ? `${x.slot}: a list${x.items ? ' of non-null items' : ''}` : `${x.slot} (${x.kind}): any value`).join('; ') || 'any value (the first stage reads it)'} | ${outText(p.out)} | no |`),
  '',
  ...Object.entries(P).flatMap(([id, p]) => [`**${id}.**`, ...p.claims.map(c => `- \`${cite(c)}\` \`${c.has}\`: ${c.claim}.`), ...(p.notRead ? [`- \`${p.notRead}\` is not read after the signature line.`] : []), '']),
  '## Candidates per task (depth ≤ 4)', '',
  '| task | M4 | M4b (rule) | by depth | types only | covered | covering | first gold depth | gold rank (code order) | bound: catch-alls only | bound: verifier\'s strict |', '|---|---|---|---|---|---|---|---|---|---|---|',
  ...shown.map(x => `| ${label(x)} | ${x.m4.total} | ${x.total} | ${x.byDepth.join(' / ')} | ${x.typedOnly} | ${x.covered ? 'yes' : 'no'} | ${x.covering.count} | ${x.covering.minDepth ?? '—'} | ${x.codeOrder.goldRank ?? '—'} | ${x.bounds.polymorphicOnly.total} (${x.bounds.polymorphicOnly.byDepth.join(' / ')}) | ${x.bounds.strictOthers.total} |`),
  '',
  '## Bounds (whatever the other eleven cards\' types)', '',
  '| bound | tasks over 100 (of 33) | W-bed tasks over 100 (of 18) | range |', '|---|---|---|---|',
  ...Object.entries(r.boundDecisions).map(([k, d]) => `| ${{ polymorphicOnly: 'P01, P12, P20, P54 alone (existential, the rule\'s reading)', polymorphicOnlyChecked: 'the same, checked reading', strictOthers: 'the verifier\'s strict input typing for the other eleven' }[k]} | ${d.tasksOver100} | ${d.wbedOver100} | ${d.min}–${d.max} |`),
  '',
  '## Diagnostics (not the rule)', '',
  '| setting | decision over 33 tasks | W-bed per task |', '|---|---|---|',
  ...Object.entries(r.diagnosticDecisions).map(([k, d]) => `| ${{ checked: 'checked reading (an unchecked output feeds no list reader)', preserveP01P54: 'P01 and P54 type-preserving (counterfactual)', checkedPreserve: 'both' }[k]} | ${dec(d)} | ${['r1', 'r2', 'r3'].map(q => `${q.toUpperCase()} ${rung(q).diagnostics[k].total}${rung(q).diagnostics[k].covered ? '' : ' (not covered)'}`).join(', ')} |`),
  '',
  '## Sensitivities on the M4b layer (not the rule)', '',
  '| setting | decision over 33 tasks |', '|---|---|',
  ...Object.entries(r.sensitivityDecisions).map(([k, d]) => `| ${{ distinct: 'a card at most once', s4Alphabet: 'alphabet = the S4 code ranker\'s shown set', depth3: 'depth ≤ 3', distinctDepth3: 'a card at most once + depth ≤ 3 (the verifier\'s row)', all: 'distinct + S4 alphabet + depth ≤ 3' }[k]} | ${dec(d)} |`),
  '',
];
if (dry) process.stdout.write(md.join('\n'));
else {
  writeFileSync(new URL('M4b-enumeration.json', OUT), JSON.stringify(r, (k, v) => (v === Infinity ? null : v), 1) + '\n');
  writeFileSync(new URL('M4b-enumeration.md', OUT), md.join('\n'));
  process.stdout.write(`wrote out/M4b-enumeration.json and .md; kill: ${r.decision.all.kill} (${r.decision.all.reasons.join('; ')})\n`);
}
